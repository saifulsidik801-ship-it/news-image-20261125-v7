#!/usr/bin/env python3
"""news-image-20261125 v7 entrypoint (stdlib only).

Copies the pre-rendered front page (entry.png, 1024x1024) into the output
directory the grader reads: $MAKEFUN_OUTPUT_DIR, else /output.
"""
import os
import shutil
import sys


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    src = os.path.join(here, "entry.png")
    out_dir = os.environ.get("MAKEFUN_OUTPUT_DIR") or "/output"
    os.makedirs(out_dir, exist_ok=True)
    dst = os.path.join(out_dir, "entry.png")
    shutil.copyfile(src, dst)
    print(f"copied {src} -> {dst} ({os.path.getsize(dst)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
